#!/usr/bin/env python3
"""Writes Tests/AetherEngineTests/ArtCNNReferenceData.swift: a synthetic line-art luma picture and what ArtCNN's
own ONNX models (C4F16, C4F32, the same revision the kernels are generated from) make of it, as the reference
`ArtCNNStageTests` compares the Metal kernels against. ONNX runs in float32 with zero padding, independently of
the GLSL translation, so a wrong weight layout or packing in the generated kernels shows as a mismatch.

    uv venv --python 3.12 /tmp/artcnn-venv && VIRTUAL_ENV=/tmp/artcnn-venv uv pip install onnx onnxruntime numpy
    /tmp/artcnn-venv/bin/python -I Scripts/artcnn-reference.py <ArtCNN checkout>/ONNX

The picture is 100x70 (not a multiple of the 12x16 threadgroups, so the edge groups are exercised). Values are
codes: 8-bit, and 10-bit for the C4F16 10-bit case. The output is quantised the way `artcnnOutput` writes it.
"""
import base64
import os
import sys

import numpy as np
import onnxruntime as ort

REVISION = '0837e5326e710f49e2ab0a8d995da0708047442e'
OUT = os.path.join(os.path.dirname(__file__), '..', 'Tests', 'AetherEngineTests', 'ArtCNNReferenceData.swift')
W, H = 100, 70


def picture():
    """Flat fills, a gradient sky, dark outlines of circles and strokes, light grain: what the network is for."""
    rng = np.random.default_rng(846)
    y, x = np.mgrid[0:H, 0:W].astype(np.float64)
    img = 0.55 + 0.25 * (y / H)                                   # sky gradient
    for cx, cy, r, fill in [(30, 35, 18, 0.85), (68, 30, 14, 0.35), (80, 55, 9, 0.7)]:
        d = np.hypot(x - cx, y - cy)
        img = np.where(d < r, fill, img)
        img = np.where(np.abs(d - r) < 1.2, 0.08, img)           # outline
    for x0, y0, x1, y1 in [(5, 60, 45, 52), (50, 8, 95, 20), (10, 10, 22, 40)]:
        t = np.clip(((x - x0) * (x1 - x0) + (y - y0) * (y1 - y0)) / ((x1 - x0) ** 2 + (y1 - y0) ** 2), 0, 1)
        d = np.hypot(x - (x0 + t * (x1 - x0)), y - (y0 + t * (y1 - y0)))
        img = np.where(d < 0.9, 0.12, img)                        # strokes
    img += rng.normal(0, 0.01, img.shape)
    return np.clip(img, 0, 1)


def run(model, luma):
    session = ort.InferenceSession(model, providers=['CPUExecutionProvider'])
    return session.run(None, {'input': luma[None, None].astype(np.float32)})[0][0, 0]


def b64(array):
    return base64.b64encode(array.tobytes()).decode()


def swift_lines(name, data):
    chunks = [data[i:i + 116] for i in range(0, len(data), 116)]
    return f'    static let {name} = """\n' + '\n'.join('    ' + c for c in chunks) + '\n    """\n'


def main():
    onnx_dir = sys.argv[1]
    img = picture()
    in8 = np.rint(img * 255).astype(np.uint8)
    in10 = np.rint(img * 1023).astype(np.uint16)
    out = {}
    for model in ('C4F16', 'C4F32'):
        y = run(os.path.join(onnx_dir, f'ArtCNN_{model}.onnx'), in8 / 255.0)
        out[f'{model.lower()}Output8'] = np.clip(np.rint(y * 255), 0, 255).astype(np.uint8)
    y10 = run(os.path.join(onnx_dir, 'ArtCNN_C4F16.onnx'), in10 / 1023.0)
    out['c4f16Output10'] = np.clip(np.rint(y10 * 1023), 0, 1023).astype('<u2')
    body = swift_lines('input8', b64(in8)) + swift_lines('input10', b64(in10.astype('<u2')))
    for k, v in out.items():
        body += swift_lines(k, b64(v))
    swift = f"""// Generated by Scripts/artcnn-reference.py from ArtCNN {REVISION} ONNX/ArtCNN_C4F16.onnx and
// ONNX/ArtCNN_C4F32.onnx (onnxruntime {ort.__version__}, float32, zero padding). Do not edit by hand.

/// A {W}x{H} synthetic line-art luma picture and ArtCNN's own output for it, row-major codes, base64:
/// `input8` / `input10` (UInt8 / little-endian UInt16 codes), `c4f16Output8` and `c4f32Output8` (8-bit, from
/// `input8`), `c4f16Output10` (10-bit, from `input10`), each {2 * W}x{2 * H}.
enum ArtCNNReferenceData {{
    static let width = {W}
    static let height = {H}

{body}}}
"""
    with open(OUT, 'w') as f:
        f.write(swift)
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
